import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve, basename } from "node:path";

// Inventory evidence, not a declaration of license compatibility or a replacement
// for the complete notices/source obligations of the binaries ultimately shipped.
const root = resolve(import.meta.dirname, "..");
const read = (file) => readFileSync(file, "utf8").replace(/^\uFEFF/, "");
const sha256 = (file) =>
  createHash("sha256").update(readFileSync(file)).digest("hex");
const metadata = spawnSync(
  process.execPath,
  [
    resolve(root, "scripts/native.mjs"),
    "metadata",
    "--locked",
    "--offline",
    "--filter-platform",
    "x86_64-pc-windows-msvc",
    "--format-version",
    "1",
  ],
  {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 30 * 1024 * 1024,
    windowsHide: true,
  },
);
if (metadata.status !== 0)
  throw new Error(
    metadata.stderr ||
      "Cargo metadata failed. Build the Windows target to populate the dependency cache first.",
  );
const graph = JSON.parse(metadata.stdout.replace(/^\uFEFF/, ""));
const selected = new Set(graph.resolve.nodes.map((node) => node.id));
const noticeFiles = (directory) =>
  readdirSync(directory, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isFile() &&
        /^(license|copying|notice|copyright|unlicense)([._-]|$)/i.test(
          entry.name,
        ),
    )
    .map((entry) => ({
      name: entry.name,
      sha256: sha256(resolve(directory, entry.name)),
    }))
    .sort((a, b) => a.name.localeCompare(b.name, "en"));
const rust = graph.packages
  .filter((pkg) => selected.has(pkg.id) && pkg.source)
  .map((pkg) => ({
    ecosystem: "cargo",
    name: pkg.name,
    version: pkg.version,
    declaredLicense: pkg.license,
    source: pkg.source,
    repository: pkg.repository,
    declaredLicenseFile: pkg.license_file ? basename(pkg.license_file) : null,
    rootNotices: noticeFiles(dirname(pkg.manifest_path)),
  }));
const lock = JSON.parse(read(resolve(root, "package-lock.json")));
const npm = Object.entries(lock.packages)
  .filter(([path, pkg]) => path && !pkg.dev)
  .map(([path, pkg]) => {
    const dir = resolve(root, path);
    const manifest = JSON.parse(read(resolve(dir, "package.json")));
    if (manifest.version !== pkg.version)
      throw new Error(`Installed package differs from lockfile: ${path}`);
    return {
      ecosystem: "npm",
      name: manifest.name,
      version: pkg.version,
      declaredLicense: pkg.license ?? manifest.license ?? null,
      source: pkg.resolved,
      integrity: pkg.integrity,
      rootNotices: noticeFiles(dir),
    };
  });
const packages = [...rust, ...npm].sort((a, b) =>
  `${a.ecosystem}:${a.name}@${a.version}`.localeCompare(
    `${b.ecosystem}:${b.name}@${b.version}`,
    "en",
  ),
);
const missingNotices = packages.filter((pkg) => pkg.rootNotices.length === 0);
const missingDeclarations = packages.filter(
  (pkg) => !pkg.declaredLicense && !pkg.declaredLicenseFile,
);
const inventory = {
  format: 1,
  target: "x86_64-pc-windows-msvc",
  inputs: {
    cargoLockSha256: sha256(resolve(root, "src-tauri/Cargo.lock")),
    npmLockSha256: sha256(resolve(root, "package-lock.json")),
  },
  scope:
    "Cargo's selected Windows graph includes build/test dependencies; npm excludes development-only packages. This is not a binary composition audit.",
  packages,
};
mkdirSync(resolve(root, "artifacts"), { recursive: true });
writeFileSync(
  resolve(root, "artifacts/dependency-license-inventory.json"),
  JSON.stringify(inventory, null, 2) + "\n",
);
const report = [
  "# Dependency license review",
  "",
  "Generated by `npm run license:inventory` from the locked, locally installed dependencies. Public-distribution review is **incomplete**.",
  "",
  `The inventory covers **${rust.length} Cargo packages** in the selected Windows graph and **${npm.length} npm packages** outside development-only dependencies. Cargo includes build/test dependencies here; these counts do not establish which code is present in the final executable.`,
  "",
  "Detailed versions, source coordinates, declared licenses, input-lockfile hashes and detected notice hashes are in `artifacts/dependency-license-inventory.json`. That generated evidence contains no local absolute paths. It must accompany the release review after regeneration.",
  "",
  `Missing package-level license declarations: **${missingDeclarations.length}**. A declaration alone does not establish complete notices or compatibility.`,
  "",
  "## Packages needing notice location review",
  "",
  "The following packages have no detected top-level LICENSE/COPYING/NOTICE file. This does not prove that their source lacks a license: inspect nested files and the exact upstream version, preserve the actual notices, and identify whether the component ships before completing this review.",
  "",
  "| Package | Version | Declared license |",
  "| --- | --- | --- |",
  ...missingNotices.map(
    (pkg) =>
      `| ${pkg.ecosystem}: ${pkg.name} | ${pkg.version} | ${String(pkg.declaredLicense ?? "Undeclared").replaceAll("|", "\\|")} |`,
  ),
  "",
  "## Remaining distribution review",
  "",
  "- Preserve complete third-party notices, including nested or vendored code and any source-availability obligations. Collecting package metadata does not satisfy those obligations.",
  "- Verify the actual Windows executable/installer composition, including WebView2 loader/runtime, Windows runtime components and NSIS tooling. They are not fully described by npm/Cargo package declarations.",
  "- Confirm SignPath's treatment of required system components and the approved installer signing structure. No SignPath eligibility approval is implied by this report.",
  "- Regenerate against each release's lockfiles and review changes. Keep public qualification incomplete until the review has evidence.",
  "",
  `Cargo lock SHA256: \`${inventory.inputs.cargoLockSha256}\``,
  "",
  `npm lock SHA256: \`${inventory.inputs.npmLockSha256}\``,
  "",
];
writeFileSync(
  resolve(root, "docs/dependency-license-review.md"),
  report.join("\n"),
);
console.log(
  JSON.stringify({
    cargo: rust.length,
    npm: npm.length,
    missingDeclarations: missingDeclarations.length,
    noticeLocationsToReview: missingNotices.length,
  }),
);
